import { Tabs as TabsPrimitive } from "@base-ui/react/tabs"
import { cva, type VariantProps } from "class-variance-authority"
import { cn } from "cn"

function Tabs({
  className,
  orientation = "horizontal",
  ...props
}: TabsPrimitive.Root.Props) {
  return (
    <TabsPrimitive.Root
      data-slot="tabs"
      data-orientation={orientation}
      className={cn(
        "group/tabs flex gap-2 data-horizontal:flex-col",
        className
      )}
      {...props}
    />
  )
}

/*
 * 横向 default 变体与 ToggleGroup 的 segmented 分段同一长相：一条轨道（细边框、background 底、2px 内边距），
 * 选中段 muted 底 + 前景色 + 加粗，未选中次要色、悬停浅底。轨道总高按 size 与同尺寸按钮相同（default h-7、lg h-8）。
 * 竖向（设置分组、工具箱的分类与工具列表）的样式不变：这些类都只在横向时生效。
 */
const tabsListVariants = cva(
  "group/tabs-list inline-flex w-fit items-center justify-center rounded-lg p-[3px] text-muted-foreground group-data-vertical/tabs:h-fit group-data-vertical/tabs:flex-col data-[variant=line]:rounded-none",
  {
    variants: {
      variant: {
        default:
          "bg-muted group-data-horizontal/tabs:gap-0.5 group-data-horizontal/tabs:border group-data-horizontal/tabs:bg-background group-data-horizontal/tabs:p-0.5",
        line: "gap-1 bg-transparent",
      },
      size: {
        default: "group-data-horizontal/tabs:h-7",
        lg: "group-data-horizontal/tabs:h-8",
      },
    },
    defaultVariants: {
      variant: "default",
      size: "default",
    },
  }
)

function TabsList({
  className,
  variant = "default",
  size = "default",
  ...props
}: TabsPrimitive.List.Props & VariantProps<typeof tabsListVariants>) {
  return (
    <TabsPrimitive.List
      data-slot="tabs-list"
      data-variant={variant}
      data-size={size}
      className={cn(tabsListVariants({ variant, size }), className)}
      {...props}
    />
  )
}

